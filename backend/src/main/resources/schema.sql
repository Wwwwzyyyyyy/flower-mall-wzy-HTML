CREATE TABLE IF NOT EXISTS account (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, username VARCHAR(40) NOT NULL UNIQUE, password_hash VARCHAR(100) NOT NULL,
 nickname VARCHAR(60) NOT NULL, phone VARCHAR(20) DEFAULT '', avatar VARCHAR(500) DEFAULT '', role VARCHAR(10) NOT NULL DEFAULT 'USER',
 status INT NOT NULL DEFAULT 1, token_version INT NOT NULL DEFAULT 0, create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS category (id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(50) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS product (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, category_id BIGINT NOT NULL, name VARCHAR(100) NOT NULL, price DECIMAL(10,2) NOT NULL,
 description TEXT, specification VARCHAR(200) NOT NULL, cover VARCHAR(500) NOT NULL, stock INT NOT NULL DEFAULT 0,
 warning_stock INT NOT NULL DEFAULT 10, status INT NOT NULL DEFAULT 1, deleted INT NOT NULL DEFAULT 0,
 create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(category_id) REFERENCES category(id),
 CHECK(price>0), CHECK(stock>=0), CHECK(warning_stock>=0)
);

CREATE TABLE IF NOT EXISTS product_image (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, product_id BIGINT NOT NULL, image_url VARCHAR(500) NOT NULL, image_type VARCHAR(10) NOT NULL DEFAULT 'detail',
 sort INT NOT NULL DEFAULT 0, FOREIGN KEY(product_id) REFERENCES product(id)
);
CREATE TABLE IF NOT EXISTS flower_language (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(50) NOT NULL, image VARCHAR(500) NOT NULL, meaning VARCHAR(500) NOT NULL,
 colors TEXT NOT NULL, culture TEXT NOT NULL, scenes VARCHAR(200) NOT NULL
);
CREATE TABLE IF NOT EXISTS product_flower_language (id BIGINT PRIMARY KEY AUTO_INCREMENT, product_id BIGINT NOT NULL, flower_id BIGINT NOT NULL, UNIQUE(product_id,flower_id));
CREATE TABLE IF NOT EXISTS address (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, user_id BIGINT NOT NULL, receiver VARCHAR(50) NOT NULL, phone VARCHAR(20) NOT NULL,
 province VARCHAR(50) NOT NULL, city VARCHAR(50) NOT NULL, district VARCHAR(50) NOT NULL, detail VARCHAR(200) NOT NULL,
 is_default INT NOT NULL DEFAULT 0, FOREIGN KEY(user_id) REFERENCES account(id)
);
CREATE TABLE IF NOT EXISTS cart (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, user_id BIGINT NOT NULL, product_id BIGINT NOT NULL, quantity INT NOT NULL,
 UNIQUE(user_id,product_id), FOREIGN KEY(user_id) REFERENCES account(id), FOREIGN KEY(product_id) REFERENCES product(id), CHECK(quantity>0)
);
CREATE TABLE IF NOT EXISTS favorite (id BIGINT PRIMARY KEY AUTO_INCREMENT, user_id BIGINT NOT NULL, product_id BIGINT NOT NULL, UNIQUE(user_id,product_id));
CREATE TABLE IF NOT EXISTS greeting (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, user_id BIGINT NOT NULL, scene VARCHAR(50) NOT NULL, receiver VARCHAR(50) NOT NULL,
 style VARCHAR(50) NOT NULL, content TEXT NOT NULL, source VARCHAR(20) NOT NULL, create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS shop_order (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, order_no VARCHAR(64) NOT NULL UNIQUE, user_id BIGINT NOT NULL, request_key VARCHAR(100) NOT NULL,
 total DECIMAL(10,2) NOT NULL, refunded DECIMAL(10,2) NOT NULL DEFAULT 0, status INT NOT NULL DEFAULT 0,
 payment_status INT NOT NULL DEFAULT 0, address_snapshot TEXT NOT NULL, greeting TEXT, remark VARCHAR(500), reject_reason VARCHAR(500),
 stock_restored INT NOT NULL DEFAULT 0, create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, pay_time TIMESTAMP NULL,
 UNIQUE(user_id,request_key), FOREIGN KEY(user_id) REFERENCES account(id)
);
CREATE TABLE IF NOT EXISTS order_item (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL, product_id BIGINT NOT NULL, name VARCHAR(100) NOT NULL,
 cover VARCHAR(500) NOT NULL, specification VARCHAR(200) NOT NULL, price DECIMAL(10,2) NOT NULL, quantity INT NOT NULL,
 FOREIGN KEY(order_id) REFERENCES shop_order(id), FOREIGN KEY(product_id) REFERENCES product(id)
);
CREATE TABLE IF NOT EXISTS payment_record (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL UNIQUE, payment_no VARCHAR(64) NOT NULL UNIQUE,
 payment_amount DECIMAL(10,2) NOT NULL, payment_method VARCHAR(50) NOT NULL DEFAULT 'MOCK', payment_status INT NOT NULL,
 transaction_no VARCHAR(100), pay_time TIMESTAMP NULL, create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(order_id) REFERENCES shop_order(id)
);
CREATE TABLE IF NOT EXISTS refund_record (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, refund_no VARCHAR(64) NOT NULL UNIQUE, order_id BIGINT NOT NULL, user_id BIGINT NOT NULL,
 refund_amount DECIMAL(10,2) NOT NULL, refund_reason VARCHAR(255) NOT NULL, refund_remark VARCHAR(500), reject_reason VARCHAR(500),
 refund_status INT NOT NULL DEFAULT 1, audit_time TIMESTAMP NULL, refund_time TIMESTAMP NULL, transaction_refund_no VARCHAR(100),
 fail_reason VARCHAR(500), auto_cancel INT NOT NULL DEFAULT 0, create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(order_id) REFERENCES shop_order(id)
);
CREATE TABLE IF NOT EXISTS stock_record (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, product_id BIGINT NOT NULL, change_type VARCHAR(30) NOT NULL, change_quantity INT NOT NULL,
 before_stock INT NOT NULL, after_stock INT NOT NULL, remark VARCHAR(255), operator_id BIGINT NOT NULL,
 create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS review (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, user_id BIGINT NOT NULL, product_id BIGINT NOT NULL, order_id BIGINT NOT NULL,
 order_item_id BIGINT NOT NULL UNIQUE, rating INT NOT NULL, content TEXT NOT NULL, status INT NOT NULL DEFAULT 1,
 deleted INT NOT NULL DEFAULT 0, create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(order_item_id) REFERENCES order_item(id), CHECK(rating BETWEEN 1 AND 5)
);
CREATE TABLE IF NOT EXISTS review_image (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, review_id BIGINT NOT NULL, image_url VARCHAR(500) NOT NULL, sort INT NOT NULL DEFAULT 0,
 FOREIGN KEY(review_id) REFERENCES review(id)
);
CREATE TABLE IF NOT EXISTS review_reply (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, review_id BIGINT NOT NULL UNIQUE, admin_id BIGINT NOT NULL, content VARCHAR(1000) NOT NULL,
 create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(review_id) REFERENCES review(id)
);
CREATE TABLE IF NOT EXISTS uploaded_file (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, owner_id BIGINT NOT NULL, purpose VARCHAR(30) NOT NULL, url VARCHAR(500) NOT NULL UNIQUE,
 create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS audit_log (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, operator_id BIGINT NOT NULL, action VARCHAR(50) NOT NULL, target_id BIGINT NOT NULL,
 reason VARCHAR(500) NOT NULL, create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS review_report (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, review_id BIGINT NOT NULL, user_id BIGINT NOT NULL, reason VARCHAR(500) NOT NULL,
 status INT NOT NULL DEFAULT 0, create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(review_id,user_id), FOREIGN KEY(review_id) REFERENCES review(id), FOREIGN KEY(user_id) REFERENCES account(id)
);

